test('complete persisted workflow: create entities, pause/resume, fail/retry, review Ready, schedule and mock-publish once', () => {
  const h = createWorkflowHarness()
  assert.equal(h.item.status, 'Idea')
  assert.deepEqual(workspaceCounts(h.state), { content: 1, scheduled: 0, published: 0, processing: 0, failed: 0, queued: 0 })
  for (const kind of ['channel', 'provider', 'pipeline']) assert.ok(h.state.activities.some(activity => activity.title === `${kind} created`))
  assert.equal(h.state.providers.get('workflow-provider').connected, false, 'No real provider connection is needed')
  const failedStep = h.state.pipelines.get('workflow-pipeline').steps.find(step => step.kind === 'Script').id
  h.start({ failAtStepId: failedStep })
  h.tick()
  assert.equal(workspaceCounts(h.state).processing, 1)
  assert.equal(canScheduleContent(h.state, h.item.id), false)
  h.command({ type: 'pause', jobId: h.run.id })
  assert.equal(workspaceCounts(h.state).processing, 0)
  h.tick(1000)
  assert.equal(h.run.execution.completedStepIds.length, 0)
  h.restore()
  assert.equal(h.run.execution.reviewBeforePublishing, true)
  assert.equal(h.run.execution.paused, true)
  h.command({ type: 'resume', jobId: h.run.id })
  h.finishPreparation()
  assert.equal(h.run.status, 'failed')
  assert.equal(h.item.status, 'Failed')
  assert.equal(workspaceCounts(h.state).failed, 1)
  assert.equal(h.run.execution.failedStepId, failedStep)
  h.restore()
  h.queueAction(h.run.id, 'retry')
  h.finishPreparation()
  assert.equal(h.run.status, 'completed')
  assert.equal(h.run.execution.progress, 100)
  assert.equal(h.item.status, 'Ready')
  assert.equal(h.state.scheduledVideos.size, 0)
  assert.equal(workspaceCounts(h.state).published, 0)
  assert.equal(workspaceCounts(h.state).failed, 0)
  assert.equal(h.run.queue.attempt, 2)
  assert.equal(h.state.activities.filter(activity => activity.title === 'Mock step started: Idea').length, 2, 'Pause/resume starts the current unfinished step again without repeating completed steps')
  assert.ok(h.run.queue.history.some(event => event.message.includes('Simulated failure')))
  assert.equal(canScheduleContent(h.state, h.item.id), true)
  assert.equal(suggestedScheduleMode(h.state, h.item.id), 'publication')
  h.operation({ type: 'save', kind: 'content', mode: 'update', value: { ...h.item, notes: 'Reviewed and approved for mock publication.' } })
  const dueAt = Date.parse('2030-01-01T10:03:00Z')
  h.operation({ type: 'save', kind: 'schedule', mode: 'create', value: { id: 'workflow-schedule', contentId: h.item.id, title: h.item.title, thumbnail: h.item.thumbnail, channelId: h.item.channelId, pipelineId: h.item.pipelineId, scheduledAt: wallTimeNow(h.state.preferences.timezone, new Date(dueAt)), status: 'Scheduled', createdAt: new Date(h.now).toISOString(), updatedAt: new Date(h.now).toISOString() } })
  const schedule = h.state.scheduledVideos.get('workflow-schedule')
  assert.equal(schedule.executionMode, 'publication', 'The Scheduler must not run the finished pipeline again')
  assert.equal(h.item.status, 'Scheduled')
  assert.equal(workspaceCounts(h.state).scheduled, 1)
  assert.equal(workspaceCounts(h.state).queued, 1)
  h.restore()
  h.now = dueAt - 1; h.tick()
  assert.equal(workspaceCounts(h.state).scheduled, 1)
  h.tick(1)
  assert.equal(workspaceCounts(h.state).processing, 1)
  assert.equal(h.state.scheduledVideos.size, 0)
  assert.equal([...h.state.jobs.values()].filter(job => job.execution).length, 1)
  h.tick(1000)
  assert.equal(h.item.status, 'Published')
  assert.deepEqual(workspaceCounts(h.state), { content: 1, scheduled: 0, published: 1, processing: 0, failed: 0, queued: 0 })
  assert.equal(channelContent(h.state, 'workflow-channel')[0].status, 'Published')
  assert.equal(pipelineJobs(h.state, 'workflow-pipeline').length, 2)
  assert.ok(h.state.activities.some(activity => activity.title === 'Scheduled content mock-published'))
  h.restore(); h.tick(10000)
  assert.equal(h.item.status, 'Published')
  assert.equal(h.state.jobs.size, 2)
  assert.ok([...h.state.jobs.values()].every(job => job.status === 'completed'))
})
test('preparation review mode works with a disconnected mock channel; scheduling still requires connection', () => {
  const h = createWorkflowHarness()
  h.operation({ type: 'save', kind: 'channel', mode: 'update', value: { ...h.state.channels.get(h.item.channelId), status: 'disconnected' } })
  h.start(); h.finishPreparation()
  assert.equal(h.item.status, 'Ready')
  const outcome = executeOperation(h.state, { type: 'save', kind: 'content', mode: 'update', value: { ...h.item, status: 'Scheduled', scheduledAt: '2099-01-01T10:00', publishPreference: 'Schedule for a date' } })
  assert.equal(outcome.result.ok, false)
  assert.ok(outcome.result.errors.channelId)
  assert.equal(outcome.state, h.state)
})
test('modified dependencies are guarded, disabled providers fail visibly, repair/retry reaches Ready', () => {
  const h = createWorkflowHarness()
  h.start(); h.tick()
  for (const op of [{ type: 'delete', kind: 'pipeline', id: h.item.pipelineId }, { type: 'delete', kind: 'provider', id: 'workflow-provider' }, { type: 'delete', kind: 'channel', id: h.item.channelId }, { type: 'save', kind: 'content', mode: 'update', value: { ...h.item, pipelineId: '' } }]) {
    const outcome = executeOperation(h.state, op)
    assert.equal(outcome.result.ok, false)
    assert.equal(outcome.state, h.state)
  }
  h.operation({ type: 'save', kind: 'provider', mode: 'update', value: { ...h.state.providers.get('workflow-provider'), enabled: false } })
  h.tick(5)
  assert.equal(h.run.status, 'failed')
  assert.ok(h.run.errorMessage.includes('provider'))
  h.operation({ type: 'save', kind: 'provider', mode: 'update', value: { ...h.state.providers.get('workflow-provider'), enabled: true } })
  h.queueAction(h.run.id, 'retry'); h.finishPreparation()
  assert.equal(h.item.status, 'Ready')
})
test('missing or invalid preparation inputs fail atomically before creating jobs', () => {
  for (const change of [state => state.channels.delete('workflow-channel'), state => state.pipelines.delete('workflow-pipeline'), state => state.providers.delete('workflow-provider'), state => state.pipelines.set('workflow-pipeline', { ...state.pipelines.get('workflow-pipeline'), enabled: false }), state => state.pipelines.set('workflow-pipeline', { ...state.pipelines.get('workflow-pipeline'), steps: [] })]) {
    const h = createWorkflowHarness(); change(h.state)
    const outcome = executePipelineCommand(h.state, { type: 'start', contentId: h.item.id, jobId: 'invalid-run', options: { reviewBeforePublishing: true } }, h.now)
    assert.equal(outcome.result.ok, false)
    assert.equal(outcome.state, h.state)
    assert.equal(h.state.jobs.size, 0)
  }
})
test('cancelled preparation remains editable and deleted content removes all pending execution work', () => {
  const h = createWorkflowHarness()
  h.start(); h.tick()
  h.queueAction(h.run.id, 'cancel')
  assert.equal(h.run.status, 'cancelled')
  assert.equal(canScheduleContent(h.state, h.item.id), false)
  h.operation({ type: 'save', kind: 'content', mode: 'update', value: { ...h.item, title: 'Revised cancelled idea' } })
  h.command({ type: 'start', contentId: h.item.id, jobId: 'replacement-run', options: { restart: true, reviewBeforePublishing: true, durationMs: 5 } })
  h.operation({ type: 'delete', kind: 'content', id: h.item.id })
  h.tick(10000)
  assert.equal(h.state.content.size, 0)
  assert.equal(h.state.jobs.size, 0)
  assert.equal(h.state.scheduledVideos.size, 0)
  assert.ok(h.state.activities.some(activity => activity.title === 'content deleted'))
})
test('review completion survives schema v4 restoration and schema v3 workspaces retain legacy run behavior', () => {
  const h = createWorkflowHarness(); h.start(); h.tick(); h.restore()
  assert.equal(h.run.execution.reviewBeforePublishing, true)
  const envelope = JSON.parse(serializeWorkspace(h.state))
  assert.equal(envelope.version, WORKSPACE_VERSION)
  assert.equal(WORKSPACE_VERSION, 4)
  envelope.version = 3
  delete envelope.workspace.jobs[0].execution.reviewBeforePublishing
  const restored = deserializeWorkspace(JSON.stringify(envelope))
  assert.equal(restored.jobs.get('workflow-run').execution.reviewBeforePublishing, undefined)
  assert.equal(restored.jobs.get('workflow-run').execution.paused, true)
})
test('review content becomes Ready only after every configured preparation step completes', () => {
  const h = createWorkflowHarness()
  h.start()
  while (h.run.execution.status !== 'COMPLETED') {
    assert.notEqual(h.item.status, 'Ready', 'Ready must not be exposed at the beginning of Quality check')
    h.tick(nextExecutionDelay(h.state, h.now))
  }
  assert.equal(h.item.status, 'Ready')
  assert.equal(h.run.execution.progress, 100)
})
