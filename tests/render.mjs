import assert from 'node:assert/strict'
import { createElement } from 'react'
import { renderToString } from 'react-dom/server'
import { createServer } from 'vite'
import { createWorkflowHarness } from './workflow.fixture.mjs'

const server = await createServer({ server: { middlewareMode: true }, appType: 'custom' })
try {
  const pages = await server.ssrLoadModule('/src/pages.tsx')
  const { StoreProvider, useStore } = await server.ssrLoadModule('/src/state/store.tsx')
  const { getMockInitialState } = await server.ssrLoadModule('/src/state/mockData.ts')
  const { ContentEditor, ChannelEditor, ScheduleEditor } = await server.ssrLoadModule('/src/components/EntityEditors.tsx')
  const { OperationFeedback, FieldError, WorkspaceFeedback, WorkspaceErrorBoundary, ResetWorkspaceDialog, useSubmission } = await server.ssrLoadModule('/src/components/feedback.tsx')
  const { MemoryRouter } = await import('react-router-dom')
  // Settings reads the hash to select its initial section.
  globalThis.window = { location: { hash: '' } }
  for (const initialState of [getMockInitialState(), { ...getMockInitialState(), channels: new Map(), content: new Map(), providers: new Map(), pipelines: new Map(), scheduledVideos: new Map(), analytics: new Map(), activities: [] }]) {
    for (const name of ['AnalyticsPage', 'ChannelsPage', 'ContentPage', 'DashboardPage', 'ProvidersPage', 'SchedulerPage', 'SettingsPage', 'WorkflowsPage']) {
      const Page = pages[name]
      const html = renderToString(createElement(MemoryRouter, null, createElement(StoreProvider, { initialState }, createElement(Page, { onCreate() {} }))))
      assert.ok(html.includes('<h1'), name)
      assert.ok(!html.includes('NaN'), name)
    }
    for (const Editor of [ContentEditor, ChannelEditor, ScheduleEditor]) {
      const html = renderToString(createElement(MemoryRouter, null, createElement(StoreProvider, { initialState }, createElement(Editor, { onClose() {} }))))
      assert.ok(html.includes('role="dialog"'))
      assert.ok(html.includes('Save changes'))
    }
  }
  const initialState = getMockInitialState()
  const close = () => {}
  const success = () => ({ ok: true, message: 'Saved.' })
  for (const [Dialog, props] of [[pages.ProviderDialog, { provider: null, onSave: success }], [pages.PipelineBuilderDialog, { pipeline: null, onSave: success }], [pages.SchedulerDetailsDialog, { item: { ...initialState.scheduledVideos.get('schedule-1'), channel: 'Mindful Minutes', pipeline: 'Shorts repurpose' }, onReschedule: success }]]) {
    const html = renderToString(createElement(MemoryRouter, null, createElement(StoreProvider, { initialState }, createElement(Dialog, { ...props, onClose: close }))))
    assert.ok(html.includes('role="dialog"'))
    if (Dialog !== pages.SchedulerDetailsDialog) assert.ok(html.includes('noValidate=""'))
  }
  console.log('PASS: all 8 pages and 6 editors/detail dialogs render, including populated and empty collections')
  const zeroViews = getMockInitialState()
  zeroViews.analytics = new Map([...zeroViews.analytics].map(([id, row]) => [id, { ...row, views: 0 }]))
  const zeroAnalyticsHtml = renderToString(createElement(MemoryRouter, null, createElement(StoreProvider, { initialState: zeroViews }, createElement(pages.AnalyticsPage))))
  assert.ok(!zeroAnalyticsHtml.includes('NaN'))
  assert.ok(!zeroAnalyticsHtml.includes('+8.4% vs. previous period'))
  console.log('PASS: zero-view analytics never render NaN or an invented period comparison')
  const failure = { ok: false, kind: 'failure', message: 'Your changes could not be saved. Please try again.', errors: {} }
  const invalid = { ok: false, kind: 'validation', message: 'Please fix the highlighted fields and try again.', errors: { title: 'Content title is required.' } }
  assert.ok(renderToString(createElement(OperationFeedback, { result: null, pending: true })).includes('role="status"'))
  assert.ok(renderToString(createElement(OperationFeedback, { result: null, pending: true })).includes('Saving changes'))
  assert.ok(renderToString(createElement(OperationFeedback, { result: { ok: true, message: 'Content created.' } })).includes('operation-success'))
  assert.ok(renderToString(createElement(OperationFeedback, { result: invalid })).includes('role="alert"'))
  assert.ok(renderToString(createElement(OperationFeedback, { result: invalid })).includes('Content title is required.'))
  assert.ok(renderToString(createElement(OperationFeedback, { result: failure })).includes('Please try again'))
  assert.ok(renderToString(createElement(OperationFeedback, { result: failure, onDismiss() {} })).includes('Dismiss message'))
  assert.ok(renderToString(createElement(FieldError, { submission: { error: () => 'Choose a channel.', errorId: () => 'channel-error' }, field: 'channelId' })).includes('id="channel-error"'))
  assert.ok(!renderToString(createElement(OperationFeedback, { result: null })))
  assert.ok(renderToString(createElement(WorkspaceErrorBoundary, null, createElement('p', null, 'Healthy view'))).includes('Healthy view'))
  let context
  function Probe({ capture }) { capture(useStore()); return null }
  renderToString(createElement(StoreProvider, { initialState: getMockInitialState() }, createElement(Probe, { capture: value => { context = value } })))
  const { actions } = context
  const value = { ...getMockInitialState().providers.get('provider-openai'), id: 'test-provider-1', name: 'Test provider' }
  assert.equal(actions.addProvider(value).ok, true)
  assert.equal(actions.addProvider({ ...value, id: 'test-provider-2' }).ok, false, 'Sequential actions must use the latest state')
  actions.requestDelete('provider', value.id)
  assert.equal(actions.updateProvider(value.id, { name: 'Still present before confirmation' }).ok, true)
  actions.cancelDelete()
  assert.equal(actions.confirmDelete().ok, false)
  assert.equal(actions.updateProvider(value.id, { name: 'Cancellation kept this provider' }).ok, true)
  actions.requestDelete('provider', value.id)
  assert.equal(actions.confirmDelete().ok, true)
  assert.equal(actions.updateProvider(value.id, { name: 'Cannot recreate a deleted provider' }).ok, false)
  assert.equal(actions.updateChannel('channel-1', { status: 'disconnected' }).ok, true)
  assert.equal(actions.togglePipeline('pipeline-long-form').ok, true)
  assert.equal(actions.updatePreferences({ defaultPipelineId: 'pipeline-long-form' }).ok, false)
  assert.equal(actions.updatePreferences({ workspaceName: '  ' }).ok, false)
  assert.equal(actions.updateContentStatus('content-1', 'Idea').ok, false)
  const shellFeedback = renderToString(createElement(StoreProvider, { initialState: getMockInitialState() }, createElement(WorkspaceFeedback)))
  assert.equal(shellFeedback, '')
  const { Select } = await server.ssrLoadModule('/src/components/ui.tsx')
  const unavailable = renderToString(createElement(Select, { value: 'deleted', onChange() {} }, createElement('option', { value: '' }, 'No default provider')))
  assert.ok(unavailable.includes('Unavailable selection'))
  assert.ok(unavailable.includes('aria-invalid="true"'))
  const { createWorkspaceSession, deserializeWorkspace, serializeWorkspace } = await server.ssrLoadModule('/src/state/persistence.ts')
  let saved = null
  const storage = { getItem: () => saved, setItem: (_key, raw) => { saved = raw } }
  const session = createWorkspaceSession(() => storage)
  renderToString(createElement(StoreProvider, { persistence: session }, createElement(Probe, { capture: value => { context = value } })))
  assert.equal(context.actions.updateChannel('channel-1', { name: 'Persistent channel' }).ok, true)
  assert.equal(deserializeWorkspace(saved).channels.get('channel-1').name, 'Persistent channel')
  const beforeRejection = saved
  assert.equal(context.actions.updateChannel('channel-1', { name: '' }).ok, false)
  context.actions.selectChannel('channel-1')
  assert.equal(saved, beforeRejection, 'Rejected operations and selections must not write storage')
  const refreshed = createWorkspaceSession(() => storage)
  renderToString(createElement(StoreProvider, { persistence: refreshed }, createElement(Probe, { capture: value => { context = value } })))
  assert.equal(context.state.channels.get('channel-1').name, 'Persistent channel')
  assert.equal(context.state.selectedChannelId, null)
  assert.equal(context.notice, null)
  assert.equal(context.pendingDelete, null)
  assert.equal(context.actions.resetState().ok, false, 'Reset requires a deliberate request')
  context.actions.requestReset()
  context.actions.cancelReset()
  assert.equal(context.actions.resetState().ok, false)
  assert.equal(saved, beforeRejection, 'Cancelled reset preserves data')
  context.actions.requestReset()
  assert.equal(context.actions.resetState().ok, true)
  assert.equal(createWorkspaceSession(() => storage).state.channels.size, 0)
  const invalidSession = createWorkspaceSession(() => ({ getItem: () => 'invalid', setItem() { assert.fail('Invalid data must not be overwritten') } }))
  const recoveryHtml = renderToString(createElement(StoreProvider, { persistence: invalidSession }, createElement(WorkspaceFeedback)))
  assert.ok(recoveryHtml.includes('could not be restored'))
  assert.ok(recoveryHtml.includes('role="alert"'))
  const resetHtml = renderToString(createElement(StoreProvider, { initialState: getMockInitialState() }, createElement(ResetWorkspaceDialog)))
  assert.ok(resetHtml.includes('role="alertdialog"'))
  assert.ok(resetHtml.includes('Keep workspace'))
  assert.ok(resetHtml.includes('Reset workspace permanently'))
  console.log('PASS: store mutations survive remount, transient state is excluded, reset is guarded and invalid-data recovery is visible')
  const { PipelineExecutionPanel } = await server.ssrLoadModule('/src/components/PipelineExecution.tsx')
  const executionState = getMockInitialState()
  executionState.content = new Map(executionState.content)
  executionState.content.set('content-8', { ...executionState.content.get('content-8'), status: 'Idea', pipelineId: 'pipeline-long-form' })
  saved = serializeWorkspace(executionState)
  const executionSession = createWorkspaceSession(() => storage)
  renderToString(createElement(StoreProvider, { persistence: executionSession }, createElement(Probe, { capture: value => { context = value } })))
  assert.equal(context.actions.startExecution('content-8', { durationMs: 10, scheduledAt: '2099-01-01T10:00' }).ok, true)
  const executionJob = [...deserializeWorkspace(saved).jobs.values()].find(job => job.execution)
  assert.ok(executionJob)
  assert.equal(executionJob.execution.reviewBeforePublishing, true, 'The application defaults to review before scheduling')
  assert.equal(context.actions.startExecution('content-8').ok, false)
  assert.equal(context.actions.updateJobStatus(executionJob.id, 'completed').ok, false)
  assert.equal(context.actions.deleteJob(executionJob.id).ok, false)
  assert.equal(context.actions.pauseExecution(executionJob.id).ok, true)
  const pausedHtml = renderToString(createElement(StoreProvider, { initialState: deserializeWorkspace(saved) }, createElement(PipelineExecutionPanel, { contentId: 'content-8' })))
  assert.ok(pausedHtml.includes('Resume'))
  assert.ok(pausedHtml.includes('Cancel execution'))
  assert.ok(pausedHtml.includes('Pipeline progress'))
  assert.equal(context.actions.resumeExecution(executionJob.id).ok, true)
  assert.equal(context.actions.failExecution(executionJob.id).ok, true)
  const failedHtml = renderToString(createElement(StoreProvider, { initialState: deserializeWorkspace(saved) }, createElement(PipelineExecutionPanel, { contentId: 'content-8' })))
  assert.ok(failedHtml.includes('Retry failed step'))
  assert.ok(failedHtml.includes('Simulated failure requested'))
  assert.equal(context.actions.retryExecution(executionJob.id).ok, true)
  assert.equal(context.actions.cancelExecution(executionJob.id).ok, true)
  assert.equal(deserializeWorkspace(saved).jobs.get(executionJob.id).execution.status, 'CANCELLED')
  const cancelledHtml = renderToString(createElement(StoreProvider, { initialState: deserializeWorkspace(saved) }, createElement(PipelineExecutionPanel, { contentId: 'content-8' })))
  assert.ok(cancelledHtml.includes('Start new mock run'))
  console.log('PASS: execution store controls persist checkpoints and render paused, failed, and cancelled states')
  const { JobQueuePanel } = await server.ssrLoadModule('/src/components/JobQueue.tsx')
  const { reconcileJobQueue, tickJobQueue } = await server.ssrLoadModule('/src/execution/queue.ts')
  const ledger = reconcileJobQueue(getMockInitialState(), Date.now())
  const queueHtml = renderToString(createElement(MemoryRouter, null, createElement(StoreProvider, { initialState: ledger }, createElement(JobQueuePanel))))
  assert.ok(queueHtml.includes('QUEUED'))
  assert.ok(queueHtml.includes('Cancel job'))
  assert.ok(queueHtml.includes('Execution history'))
  saved = serializeWorkspace(ledger)
  renderToString(createElement(StoreProvider, { persistence: createWorkspaceSession(() => storage) }, createElement(Probe, { capture: value => { context = value } })))
  const pendingJob = [...ledger.jobs.values()].find(job => job.queue && job.status === 'pending')
  assert.equal(context.actions.cancelQueueJob(pendingJob.id).ok, true)
  assert.equal(deserializeWorkspace(saved).jobs.get(pendingJob.id).status, 'cancelled')
  assert.equal(deserializeWorkspace(saved).scheduledVideos.has(pendingJob.queue.scheduleId), false)
  let failedQueue = { ...ledger, channels: new Map([...ledger.channels].map(([id, channel]) => [id, { ...channel, status: 'disconnected' }])) }
  failedQueue = tickJobQueue(failedQueue, Date.parse('2098-01-01T10:00:00Z'))
  const failedQueueHtml = renderToString(createElement(MemoryRouter, null, createElement(StoreProvider, { initialState: failedQueue }, createElement(JobQueuePanel))))
  assert.ok(failedQueueHtml.includes('FAILED'))
  assert.ok(failedQueueHtml.includes('Retry job'))
  assert.ok(failedQueueHtml.includes('disconnected'))
  saved = serializeWorkspace(failedQueue)
  renderToString(createElement(StoreProvider, { persistence: createWorkspaceSession(() => storage) }, createElement(Probe, { capture: value => { context = value } })))
  const failedQueueJob = [...failedQueue.jobs.values()].find(job => job.status === 'failed')
  const retryChannelId = failedQueue.content.get(failedQueueJob.contentId).channelId
  assert.equal(context.actions.updateChannel(retryChannelId, { status: 'connected' }).ok, true)
  assert.equal(context.actions.retryQueueJob(failedQueueJob.id).ok, true)
  const retriedQueue = deserializeWorkspace(saved).jobs.get(failedQueueJob.id)
  assert.equal(retriedQueue.status, 'pending')
  assert.equal(retriedQueue.queue.type, 'RETRY')
  assert.equal(retriedQueue.queue.attempt, 2)
  console.log('PASS: queue cancellation/retry persist through store actions and queue/history/error controls render')
  const { PipelineDetailsDialog } = await server.ssrLoadModule('/src/components/PipelineDetails.tsx')
  const { useChannelRows, useDashboardData } = await server.ssrLoadModule('/src/state/adapters.ts')
  const { workspaceCounts } = await server.ssrLoadModule('/src/state/selectors.ts')
  const journey = createWorkflowHarness()
  const views = new Map([['idea', journey.state]])
  journey.start({ failAtStepId: journey.state.pipelines.get('workflow-pipeline').steps.find(step => step.kind === 'Script').id })
  journey.tick()
  views.set('processing', journey.state)
  journey.command({ type: 'pause', jobId: journey.run.id })
  views.set('paused', journey.state)
  journey.command({ type: 'resume', jobId: journey.run.id }); journey.finishPreparation()
  views.set('failed', journey.state)
  journey.queueAction(journey.run.id, 'retry'); journey.finishPreparation()
  views.set('ready', journey.state)
  const ready = journey.state
  const renderView = (initialState, View, props = {}, path = '/content?content=workflow-content') => renderToString(createElement(MemoryRouter, { initialEntries: [path] }, createElement(StoreProvider, { initialState }, createElement(View, props))))
  for (const [stage, initialState] of views) {
    const html = renderView(initialState, pages.ContentPage)
    assert.ok(html.includes('Workflow Idea'), stage)
    assert.ok(html.includes('content-details-title'), stage)
    assert.ok(html.includes('Workflow Provider'), `${stage}: configured step provider is inspectable`)
    if (stage === 'idea') assert.ok(html.includes('Finish at Ready for review, then schedule'))
    if (stage === 'processing') assert.ok(html.includes('Pipeline progress'))
    if (stage === 'paused') assert.ok(html.includes('Resume'))
    if (stage === 'failed') assert.ok(html.includes('Retry failed step'))
    if (stage === 'ready') assert.ok(html.includes('Schedule ready content'))
    const pipelineHtml = renderView(initialState, PipelineDetailsDialog, { pipelineId: 'workflow-pipeline', onClose() {} })
    assert.ok(pipelineHtml.includes('Workflow Pipeline'))
    if (stage !== 'idea') assert.ok(pipelineHtml.includes('workflow-run'), `${stage}: pipeline details show the actual run`)
  }
  const preselectedSchedule = renderView(ready, ScheduleEditor, { initialContentId: 'workflow-content', onClose() {} })
  assert.ok(preselectedSchedule.includes('value="publication" selected=""'))
  assert.ok(preselectedSchedule.includes('value="workflow-content" selected=""'))
  journey.operation({ type: 'save', kind: 'content', mode: 'update', value: { ...journey.item, status: 'Scheduled', scheduledAt: '2030-01-01T15:33', publishPreference: 'Schedule for a date' } })
  const scheduledJourney = journey.state
  assert.equal([...scheduledJourney.scheduledVideos.values()][0].executionMode, 'publication')
  assert.ok(renderView(scheduledJourney, pages.ContentPage).includes('View scheduled job'))
  assert.ok(renderView(scheduledJourney, pages.SchedulerPage).includes('SCHEDULED_PUBLICATION'))
  journey.now = Date.parse('2030-01-01T10:03:00Z'); journey.tick(); journey.tick(1000)
  const publishedJourney = journey.state
  assert.ok(renderView(publishedJourney, pages.ContentPage).includes('Mock publication complete'))
  let channelView
  let dashboardView
  function SharedProjectionProbe({ capture }) { capture({ channel: useChannelRows()[0], dashboard: useDashboardData() }); return null }
  for (const initialState of [ready, scheduledJourney, publishedJourney]) {
    renderView(initialState, SharedProjectionProbe, { capture: value => { channelView = value.channel; dashboardView = value.dashboard } })
    const counts = workspaceCounts(initialState)
    assert.equal(dashboardView.overview.find(row => row.label === 'Videos published').value, String(counts.published))
    assert.equal(dashboardView.overview.find(row => row.label === 'Videos scheduled').value, String(counts.scheduled))
    assert.equal(channelView.publishedCount, counts.published)
    assert.equal(channelView.scheduledCount, counts.scheduled)
    const channelHtml = renderView(initialState, pages.ChannelDetailsDialog, { channel: channelView, onClose() {}, onConnect() {} })
    assert.ok(channelHtml.includes('/content?content=workflow-content'))
    assert.ok(channelHtml.includes('Associated content'))
    assert.ok(renderView(initialState, pages.DashboardPage, { onCreate() {} }, '/').includes('View activity history'))
  }
  assert.equal(channelView.recentActivity, publishedJourney.activities[0].title)
  assert.ok(dashboardView.activityHistory.some(activity => activity.title === 'Scheduled content mock-published'))
  assert.ok(renderView(ready, pages.ContentPage, {}, '/content?content=deleted-content').includes('Content unavailable'))
  console.log('PASS: complete workflow views share counters, deep links, step details, Ready handoff, publication-only scheduling, failure controls, and final publication state')
  let submission
  function SubmissionProbe({ capture }) { capture(useSubmission()); return null }
  renderToString(createElement(SubmissionProbe, { capture: value => { submission = value } }))
  globalThis.window.setTimeout = globalThis.setTimeout
  let writes = 0
  const firstSave = submission.submit(() => { writes += 1; return { ok: true, message: 'Saved.' } })
  const secondSave = submission.submit(() => { writes += 1; return { ok: true, message: 'Saved twice.' } })
  const outcomes = await Promise.all([firstSave, secondSave])
  assert.equal(writes, 1)
  assert.equal(outcomes[0].ok, true)
  assert.equal(outcomes[1].ok, false)
  const failedSubmission = await submission.submit(() => { throw new Error('Internal diagnostic details') })
  assert.equal(failedSubmission.ok, false)
  assert.equal(JSON.stringify(failedSubmission).includes('Internal diagnostic details'), false)
  console.log('PASS: loading, success, validation, failure, empty feedback, accessible field errors, and unavailable selections render correctly')
  console.log('PASS: repeated submissions are prevented and thrown operation errors are sanitized')
  console.log('PASS: store actions serialize updates, require deletion confirmation, and preserve data on cancel or rejection')
} finally {
  delete globalThis.window
  await server.close()
}
